ALTER TABLE "DifficultyPricing" DROP CONSTRAINT IF EXISTS "DifficultyPricing_field_check";

DO $$
DECLARE
  difficulty_check record;
BEGIN
  FOR difficulty_check IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public."DifficultyPricing"'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%difficulty%'
  LOOP
    EXECUTE format('ALTER TABLE "DifficultyPricing" DROP CONSTRAINT %I', difficulty_check.conname);
  END LOOP;
END $$;

