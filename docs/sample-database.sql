CREATE OR REPLACE FUNCTION public.assign_freelancer_for_account()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  next_freelancer_id integer;
BEGIN
  IF NEW."role" IN ('Freelancer', 'QC') AND NEW."freelancerId" IS NULL THEN
    SELECT COALESCE(MAX("fIld"), 0) + 1 INTO next_freelancer_id FROM "Freelancer";
    INSERT INTO "Freelancer" ("fIld", "name", "email", "field", "fields")
    VALUES (next_freelancer_id, NEW."displayName", NEW."email", NEW."field", NEW."fields");
    NEW."freelancerId" := next_freelancer_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "Accounts_assign_freelancer" ON "Accounts";
CREATE TRIGGER "Accounts_assign_freelancer"
BEFORE INSERT OR UPDATE OF "role", "freelancerId"
ON "Accounts"
FOR EACH ROW
EXECUTE FUNCTION public.assign_freelancer_for_account();

CREATE OR REPLACE FUNCTION public.sync_account_to_freelancer()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW."role" IN ('Freelancer', 'QC') AND NEW."freelancerId" IS NOT NULL THEN
    UPDATE "Freelancer"
    SET "name" = NEW."displayName",
        "email" = NEW."email",
        "field" = NEW."field",
        "fields" = NEW."fields"
    WHERE "fIld" = NEW."freelancerId";
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "Accounts_sync_freelancer" ON "Accounts";
CREATE TRIGGER "Accounts_sync_freelancer"
AFTER INSERT OR UPDATE OF "role", "displayName", "email", "field", "fields", "freelancerId"
ON "Accounts"
FOR EACH ROW
EXECUTE FUNCTION public.sync_account_to_freelancer();

-- Keep QC dropdown options synchronized with accounts that have role QC.
CREATE OR REPLACE FUNCTION public.sync_account_to_qc()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW."role" = 'QC' THEN
    INSERT INTO "QC" ("qcId", "name", "email")
    VALUES (NEW."id"::integer, NEW."displayName", NEW."email")
    ON CONFLICT ("qcId") DO UPDATE
      SET "name" = EXCLUDED."name", "email" = EXCLUDED."email";
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "Accounts_sync_qc" ON "Accounts";
CREATE TRIGGER "Accounts_sync_qc"
AFTER INSERT OR UPDATE OF "role", "displayName", "email"
ON "Accounts"
FOR EACH ROW
EXECUTE FUNCTION public.sync_account_to_qc();

